"""Build and validate the catalogue's derived views from Markdown records."""
from pathlib import Path
import csv
import io
import json
import re
import sys
from collections import Counter
from urllib.parse import unquote, urlsplit
import yaml

ROOT = Path(__file__).resolve().parents[1]
KINDS = ('instruments', 'papers', 'families', 'patterns')


def read_record(path):
    text = path.read_text(encoding='utf-8')
    if not text.startswith('---\n'):
        return None
    _, front, body = text.split('---', 2)
    meta = yaml.safe_load(front)
    return dict(meta, path=path.relative_to(ROOT).as_posix(), body=body.strip())


def load():
    return {kind: [r for p in sorted((ROOT/'catalog'/kind).glob('*.md'))
                   if (r := read_record(p))] for kind in KINDS}


def cell(value):
    return re.sub(r'(?<!\\)\|', r'\\|', str(value)).replace('\n', ' ').strip()


def table(headers, rows):
    return '\n'.join(['| '+' | '.join(headers)+' |',
                      '| '+' | '.join('---' for _ in headers)+' |'] +
                     ['| '+' | '.join(cell(v) for v in row)+' |' for row in rows])+'\n'


def link(record, base='../'):
    title = record['title'].replace('[', '\\[').replace(']', '\\]')
    return f"[{record['id']}: {title}]({base}{record['path']})"


def generated(title, content):
    return '# '+title+'\n\n<!-- Generated by scripts/build_indexes.py; edit catalogue records instead. -->\n\n'+content.rstrip()+'\n'


def views(data):
    families = sorted(data['families'], key=lambda r:r['id'])
    instruments = data['instruments']; papers = data['papers']; patterns = data['patterns']
    outputs = {}
    inventory_path = ROOT/'sources/release-inventory.json'
    if inventory_path.exists():
        inventory = json.loads(inventory_path.read_text(encoding='utf-8'))
        indexed = {r['source_family']: r for r in families}
        covered = sum(f['family'] in indexed for f in inventory['families'])
        pending = len(inventory['families'])-covered
        subject_totals = Counter(f['subject'] for f in inventory['families'])
        subject_covered = Counter(f['subject'] for f in inventory['families'] if f['family'] in indexed)
        subject_rows = [[subject, subject_totals[subject], subject_covered[subject],
                         subject_totals[subject]-subject_covered[subject]]
                        for subject in sorted(subject_totals)]
        coverage_rows = []
        for f in inventory['families']:
            r = indexed.get(f['family'])
            status = r['batch_id'] if r else 'Pending'
            target = f"../{r['path']}" if r else f"https://github.com/openai/math/blob/{inventory['source_commit']}/CONTENTS.md"
            coverage_rows.append([f"[{f['family']}: {f['title']}]({target})", f['subject'], len(f['papers']), status])
        outputs['tables/coverage.md'] = generated('Release coverage',
            f"The pinned release contains {inventory['family_count']} families and {inventory['unique_manuscript_count']} distinct manuscripts. The catalogue contains selected extractions for **{covered} families**; **{pending} families remain pending**.\n\n"+
            'Coverage means that selected instruments have been described. It does not mean every argument or companion manuscript has been independently reviewed. B001 imports the direction paper; later batches record their own source passages and review scope. The source-paper index and batch manifests give the manuscript-level detail.\n\n'+
            '## Coverage by subject\n\n'+
            table(['Subject', 'Release families', 'Catalogued families', 'Pending families'], subject_rows)+
            '\n## Family details\n\n'+
            table(['Family', 'Subject', 'Source manuscripts', 'Extraction batch'], coverage_rows))
    outputs['tables/instruments.md'] = generated('Mathematical instruments',
        'Form labels describe the presentation of an instrument. Novelty and mathematical review are recorded separately.\n\n'+
        table(['Instrument', 'Form', 'Subject', 'Family', 'Reuse'],
        [[link(r), ', '.join(r['forms']), r['subject'], ', '.join(f'[{f}](../catalog/families/{f}.md)' for f in r['family_ids']), r['reuse_status']] for r in instruments]))
    outputs['tables/papers.md'] = generated('Source manuscripts',
        'These records include principal and companion manuscripts. B001 extraction descriptions are organized by family; paper counts do not measure independent extraction or verification.\n\n'+
        table(['Manuscript', 'Family', 'Source date', 'Coverage'],
        [[link(r), ', '.join(f'[{f}](../catalog/families/{f}.md)' for f in r['family_ids']), r.get('source_date') or 'See source', r['coverage']] for r in papers]))
    outputs['tables/families.md'] = generated('Problem families',
        table(['Family', 'Subject', 'Instruments', 'Novelty assessment', 'Batch'],
        [[link(r),r['subject'],len(r['instrument_ids']),r['novelty_assessment'],r['batch_id']] for r in families]))
    for group,word in [(1,'first'),(2,'second')]:
        outputs[f'tables/map-{word}-group.md'] = generated(f'Initial family map: {word} group',
            'The initial groups contain 17 and 21 families. Both belong to the initial extraction. Headline statements report source claims.\n\n'+
            table(['Family', 'Result', 'Formalization', 'Central extracted instrument', 'Verdict'],
            [[f"[{r['source_family']}](../{r['path']})",r['headline'],r.get('map_formalization_summary',r['formalization_summary']),r['central_instrument'],r['novelty_assessment']] for r in families if r.get('original_group')==group]))
    outputs['tables/formalization-and-review.md'] = generated('Formalization and review',
        'Supplied formalizations, inspected statements, successful builds and kernel checking are different kinds of evidence. No Lean project was built for the initial extraction or repository import. The historical 19 headline labels include partial inspection for families 003 and 087; they are not 19 certified family proofs.\n\n'+
        table(['Family', 'Formalization', 'Statement coverage', 'Dependencies', 'Antecedents'],
        [[link(r),r['formalization_summary'],r['statement_faithfulness'],r['dependencies'],r['antecedents']] for r in families]))
    outputs['tables/dependencies-and-antecedents.md'] = generated('Dependencies and antecedents',
        table(['Family', 'Dependencies', 'Antecedents and comparisons'],
        [[link(r),r['dependencies'],r['antecedents']] for r in families]))
    outputs['tables/overview.md'] = generated('Catalogue overview',
        table(['Record', 'Count'],[[k.capitalize(),len(data[k])] for k in KINDS])+
        '\nThe 38 initial families form groups of 17 and 21. The initial paper reports 19 original headline-formalization labels, including two partially inspected families, and five companion-only labels when family 159 is counted. These historical labels are distinct from current evidence. Mixed novelty assessments are retained without an aggregate novelty total.\n\n'+
        '[Original four tables and their qualifications](../editions/zenodo-23319145/published-tables.md) · [Assessment method](../methodology/assessment.md)\n')
    outputs['catalog/patterns/README.md'] = generated('Recurring patterns',
        '\n'.join(f"- [{r['title']}]({Path(r['path']).name})" for r in patterns))
    for kind in ['instruments','papers','families']:
        outputs[f'catalog/{kind}/README.md'] = f'# {kind.capitalize()}\n\n[Browse the {kind} index](../../tables/{kind}.md).\n\nThese Markdown records contain the canonical metadata and descriptions. Generated indexes and exports are rebuilt from them.\n'
    export={'schema_version':'1.0','direction_paper':'https://zenodo.org/records/23319145',**data}
    outputs['exports/catalog.json']=json.dumps(export,ensure_ascii=False,indent=2)+'\n'
    for kind in ['instruments','papers','families']:
        fields={'instruments':['id','title','forms','subject','family_ids','source_paper_ids','novelty_status','review_status','reuse_status','case_study_ids','batch_id','path'],
                'papers':['id','title','family_ids','source_url','source_version','source_date','coverage','batch_id','path'],
                'families':['id','title','subject','instrument_ids','source_paper_ids','novelty_assessment','formalization_summary','batch_id','path']}[kind]
        out=io.StringIO(newline='');writer=csv.DictWriter(out,fieldnames=fields,lineterminator='\n');writer.writeheader()
        for r in data[kind]:
            writer.writerow({k:'; '.join(r[k]) if isinstance(r.get(k),list) else r.get(k,'') for k in fields})
        outputs[f'exports/{kind}.csv']=out.getvalue()
    readme_path=ROOT/'README.md'
    if readme_path.exists():
        readme=readme_path.read_text(encoding='utf-8')
        start='<!-- catalogue-navigation:start -->'
        end='<!-- catalogue-navigation:end -->'
        if start in readme and end in readme:
            nav=table(['Browse','Contents'],[
                ['[Mathematical instruments](tables/instruments.md)',f'{len(instruments)} extracted entries, each with a stable identifier'],
                ['[Source papers](tables/papers.md)',f'{len(papers)} manuscript records across the selected families'],
                ['[Problem families](tables/families.md)',f'{len(families)} family accounts with claims, antecedents and caveats'],
                ['[Recurring patterns](catalog/patterns/README.md)',f'{len(patterns)} approaches connecting the source arguments'],
                ['[Tables and review status](tables/README.md)','Family maps, formalization, dependencies and antecedents'],
                ['[Extraction batches](batches/README.md)','Extraction rounds and source versions'],
                *([['[Release coverage](tables/coverage.md)', f'{covered} of {inventory["family_count"]} families catalogued; {pending} pending']] if inventory_path.exists() else []),
                ['[Use case studies](case-studies/README.md)','Subsequent investigations using extracted instruments'],
                ['[Catalogue exports](exports/README.md)','JSON and CSV for search and further analysis'],
            ])
            outputs['README.md']=readme.split(start)[0]+start+'\n\n'+nav+'\n'+end+readme.split(end,1)[1]
    return outputs


def build(check=False):
    outputs=views(load());changed=[]
    for relative,text in outputs.items():
        p=ROOT/relative
        if not p.exists() or p.read_text(encoding='utf-8')!=text:
            changed.append(relative)
            if not check:
                p.parent.mkdir(parents=True,exist_ok=True)
                p.write_text(text,encoding='utf-8',newline='\n')
    if check and changed:
        raise ValueError('Generated files need rebuilding: '+', '.join(changed))
    return len(outputs),changed


def validate():
    data=load();all_records=[r for values in data.values() for r in values]
    ids=[r['id'] for r in all_records]
    if len(ids)!=len(set(ids)):raise ValueError('Duplicate record identifiers')
    by_id={r['id']:r for r in all_records}
    for kind,records in data.items():
        singular={'instruments':'instrument','papers':'paper','families':'family','patterns':'pattern'}[kind]
        for r in records:
            required={'id','record_type','title','batch_id','updated'}
            assert required<=r.keys(),(r.get('id'),required-r.keys())
            assert r['record_type']==singular,r['id']
            assert r['title'] and r['body'],r['id']
            pattern={'instruments':r'MI-\d{6}','papers':r'P-\d{6}','families':r'[a-z0-9]+(?:-[a-z0-9]+)+','patterns':r'PAT-\d{3}'}[kind]
            assert re.fullmatch(pattern,r['id']),r['id']
            for field in ['family_ids','source_paper_ids','instrument_ids']:
                for target in r.get(field,[]):assert target in by_id,(r['id'],field,target)
            assert (ROOT/'batches'/r['batch_id']/'manifest.yaml').is_file(),r['id']
    for r in data['instruments']:
        for fid in r['family_ids']:assert r['id'] in by_id[fid]['instrument_ids'],r['id']
        for pid in r['source_paper_ids']:
            assert set(r['family_ids']) & set(by_id[pid]['family_ids']),(r['id'],pid)
    for r in data['families']:
        for mid in r['instrument_ids']:assert r['id'] in by_id[mid]['family_ids'],r['id']
        for pid in r['source_paper_ids']:assert r['id'] in by_id[pid]['family_ids'],r['id']
    for p in (ROOT/'batches').glob('*/manifest.yaml'):
        batch=yaml.safe_load(p.read_text(encoding='utf-8'))
        for field in ['family_ids','instrument_ids','paper_ids']:
            for rid in batch[field]:assert rid in by_id,(p,rid)
        for kind, field in [('families','family_ids'),('instruments','instrument_ids'),('papers','paper_ids')]:
            for r in data[kind]:
                if r['batch_id']==batch['id']:
                    assert r['id'] in batch[field],('Record missing from its batch',r['id'])
        source_manifest=ROOT/'sources/batches'/f"{batch['id']}.json"
        if source_manifest.exists():
            source_data=json.loads(source_manifest.read_text(encoding='utf-8'))
            assert source_data['source_commit']==batch['source_commit']
            files={r['path']:r for r in source_data['files']}
            for locator in source_data['instrument_locators']:
                assert locator['instrument_id'] in batch['instrument_ids']
                assert locator['sha256']==files[locator['path']]['sha256']
                assert locator['line']>=1 and f"/{batch['source_commit']}/" in locator['url']
            for mid in batch['instrument_ids']:
                r=by_id[mid]
                if r['batch_id']==batch['id']:
                    assert r.get('source_locations'),('Missing exact source locations',mid)
                    actual=[{k:v for k,v in loc.items() if k!='instrument_id'} for loc in source_data['instrument_locators'] if loc['instrument_id']==mid]
                    assert r['source_locations']==actual,('Source locator mismatch',mid)
    case_ids=set()
    for p in (ROOT/'case-studies').glob('*/metadata.yaml'):
        case=yaml.safe_load(p.read_text(encoding='utf-8'))
        assert case['id'] not in case_ids,case['id']
        case_ids.add(case['id'])
        for mid in case['instrument_ids']:
            assert case['id'] in by_id[mid]['case_study_ids'],(p,mid)
    for r in data['instruments']:
        assert set(r['case_study_ids'])<=case_ids,(r['id'],r['case_study_ids'])
    forbidden=re.compile(r'claude\.ai|sandbox:|file://|[A-Z]:[\\/](?:users|Users)|turn\d+(?:search|view)|INSTRUMENT-LINK|\x00')
    broken=[]
    for p in ROOT.rglob('*.md'):
        if '.git' in p.parts:continue
        text=p.read_text(encoding='utf-8')
        assert not forbidden.search(text),f'Private path or drafting residue: {p}'
        # Templates deliberately show example paths that do not exist yet.
        if 'templates' in p.relative_to(ROOT).parts:continue
        text=re.sub(r'```.*?```','',text,flags=re.S)
        for target in re.findall(r'\]\(([^\s)]+)(?:\s+"[^"]*")?\)',text):
            target=target.strip('<>');parsed=urlsplit(target)
            if parsed.scheme or target.startswith('#'):continue
            dest=(p.parent/unquote(parsed.path)).resolve()
            if not dest.exists():broken.append((p.relative_to(ROOT).as_posix(),target))
    assert not broken,'Broken local links: '+repr(broken[:20])
    from hashlib import sha256
    fixed=ROOT/'editions/zenodo-23319145'
    coverage=yaml.safe_load((fixed/'coverage.yaml').read_text(encoding='utf-8'))
    assert sha256((fixed/coverage['import_source']).read_bytes()).hexdigest()==coverage['import_source_sha256']
    assert sha256((fixed/coverage['import_pdf']).read_bytes()).hexdigest()==coverage['import_pdf_sha256']
    initial=yaml.safe_load((ROOT/'batches/B001/manifest.yaml').read_text(encoding='utf-8'))
    assert len(initial['instrument_ids'])==coverage['instruments']
    assert len(initial['family_ids'])==coverage['families']
    assert len(initial['paper_ids'])==coverage['source_paper_records']
    build(check=True)
    return {k:len(v) for k,v in data.items()}
